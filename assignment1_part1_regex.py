"""## Question 7 (3 points)

Extract the date of every note and sort the notes chronologically.

**Rules**
- `xx/xx/xx` is `mm/dd/yy`.
- A 2-digit year is in the 1900s (`1/5/89` is January 5th, 1989).
- When the day is missing (`9/2009`, `Feb 2009`), use the first day of the month.
- When the month is missing (`2010`), use January 1st.

`question_seven()` returns a `pandas.Series` of length 500 whose **values are the original indices** of the notes, in ascending chronological order.

Example: if the notes were `0: "1999"`, `1: "2010"`, `2: "1978"`, the function returns the Series `[2, 0, 1]`.
"""

def question_seven():
    """Series of the 500 note indices sorted by date."""
    parsed_dates = []

    # Month map for text month names
    month_map = {
        'jan': 1, 'feb': 2, 'mar': 3, 'apr': 4, 'may': 5, 'jun': 6,
        'jul': 7, 'aug': 8, 'sep': 9, 'oct': 10, 'nov': 11, 'dec': 12
    }

    for idx, note in enumerate(df):
        # 1. MM/DD/YY or MM/DD/YYYY
        match1 = re.search(r"\b(0?[1-9]|1[0-2])[\/\-](0?[1-9]|[12]\d|3[01])[\/\-](\d{4}|\d{2})\b", note)
        if match1:
            m, d, y = int(match1.group(1)), int(match1.group(2)), int(match1.group(3))
            if y < 100:
                y += 1900
            parsed_dates.append((idx, datetime(y, m, d)))
            continue

        # 2. DD Month YYYY (e.g. 20 Mar 2009)
        match2 = re.search(r"\b(\d{1,2})[-., ]+(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*(?:[., ]+)?(\d{4})\b", note, re.IGNORECASE)
        if match2:
            d, m_str, y = int(match2.group(1)), match2.group(2).lower()[:3], int(match2.group(3))
            m = month_map[m_str]
            parsed_dates.append((idx, datetime(y, m, d)))
            continue

        # 3. Month DD, YYYY (e.g. Mar-20-2009 or Mar 20, 2009)
        match3 = re.search(r"\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*[-., ]+(\d{1,2})(?:st|nd|rd|th)?[-., ]+(\d{4})\b", note, re.IGNORECASE)
        if match3:
            m_str, d, y = match3.group(1).lower()[:3], int(match3.group(2)), int(match3.group(3))
            m = month_map[m_str]
            parsed_dates.append((idx, datetime(y, m, d)))
            continue

        # 4. Month YYYY (e.g. Feb 2009)
        match4 = re.search(r"\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*[-., ]+(\d{4})\b", note, re.IGNORECASE)
        if match4:
            m_str, y = match4.group(1).lower()[:3], int(match4.group(2))
            m = month_map[m_str]
            parsed_dates.append((idx, datetime(y, m, 1)))
            continue

        # 5. MM/YYYY (e.g. 6/2008)
        match5 = re.search(r"\b(0?[1-9]|1[0-2])\/(\d{4})\b", note)
        if match5:
            m, y = int(match5.group(1)), int(match5.group(2))
            parsed_dates.append((idx, datetime(y, m, 1)))
            continue

        # 6. YYYY (e.g. 2009)
        match6 = re.search(r"\b(\d{4})\b", note)
        if match6:
            y = int(match6.group(1))
            parsed_dates.append((idx, datetime(y, 1, 1)))
            continue

        # Fallback if nothing matches
        parsed_dates.append((idx, datetime(1900, 1, 1)))

    # Sort chronologically, keep index
    sorted_notes = sorted(parsed_dates, key=lambda x: (x[1], x[0]))
    return pd.Series([val[0] for val in sorted_notes])

