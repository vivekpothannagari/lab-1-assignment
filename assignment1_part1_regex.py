"""## Question 5 (1 point)

`question_five(text)` cleans a text: remove digits, remove punctuation, lowercase, normalize whitespace.
"""

def question_five(text):
    """Cleaned text: no digit, no punctuation, lowercase, single spaces."""
    # Remove digits
    text_no_digits = re.sub(r'\d+', '', text)
    # Remove punctuation (replace with spaces to avoid joining words, or simply remove)
    text_no_punc = re.sub(r'[!"#$%&\'()*+,-./:;<=>?@[\\\]^_`{|}~]', ' ', text_no_digits)
    # Convert to lowercase
    text_lower = text_no_punc.lower()
    # Normalize whitespace to single spaces and strip leading/trailing spaces
    cleaned = re.sub(r'\s+', ' ', text_lower).strip()
    return cleaned

