"""## Question 1 (1 point)

Lexical diversity: number of distinct tokens divided by the number of tokens. *Returns a float.*
"""

def question_one():
    # Calculate the lexical richness of the text
    unique_tokens = len(set(moby_tokens))
    total_tokens = len(moby_tokens)
    return unique_tokens / total_tokens

print(question_one())

"""## Question 2 (1 point)

Percentage of tokens equal to `whale` or `Whale`. *Returns a float (e.g. 0.5 for 0.5 %).*
"""

def question_two():
    # Count occurrences of 'whale' and 'Whale' in the token list
    target_words = {'whale', 'Whale'}
    matches = sum(1 for token in moby_tokens if token in target_words)
    return (matches / len(moby_tokens)) * 100

print(question_two())

"""## Question 3 (1 point)

The 20 most frequent tokens and their frequency. *Returns a list of 20 `(token, frequency)` tuples sorted by decreasing frequency.*
"""

def question_three():
    # Extract the 20 most frequent tokens overall
    distribution = nltk.FreqDist(moby_tokens)
    return distribution.most_common(20)

print(question_three())

"""## Question 4 (1 point)

Tokens longer than 5 characters with a frequency above 150. *Returns an alphabetically sorted list of tokens.*
"""

def question_four():
    # Filter tokens longer than 5 chars with frequency > 150
    distribution = nltk.FreqDist(moby_tokens)
    filtered = [w for w, count in distribution.items() if len(w) > 5 and count > 150]
    return sorted(filtered)

print(question_four())

"""## Question 5 (1 point)

The longest token and its length. *Returns a `(token, length)` tuple.*
"""

def question_five():
    # Find the longest word and get its size
    longest_word = max(moby_tokens, key=len)
    return (longest_word, len(longest_word))

print(question_five())

"""## Question 6 (1 point)

Alphabetic tokens (`isalpha()`) with a frequency above 2000. *Returns a list of `(frequency, word)` tuples sorted by decreasing frequency.*
"""

def question_six():
    # Find alphabetic tokens with a frequency higher than 2000
    distribution = nltk.FreqDist(moby_tokens)
    high_freq_words = []
    for word, count in distribution.items():
        if word.isalpha() and count > 2000:
            high_freq_words.append((count, word))
    return sorted(high_freq_words, reverse=True)

print(question_six())

"""## Question 7 (1 point)

Average number of tokens per sentence (`sent_tokenize` for the sentences). *Returns a float.*
"""

def question_seven():
    # Get sentence count and divide total tokens by it
    total_sentences = len(nltk.sent_tokenize(moby_raw))
    total_tokens = len(moby_tokens)
    return total_tokens / total_sentences

print(question_seven())

"""## Question 8 (1 point)

The 10 most frequent lowercase alphabetic tokens after removing the English stop words. *Returns a list of 10 `(word, frequency)` tuples sorted by decreasing frequency.*
"""

def question_eight():
    # Clean and filter stop words
    english_stops = set(stopwords.words("english"))
    cleaned_words = [
        word.lower() for word in moby_tokens
        if word.isalpha() and word.lower() not in english_stops
    ]
    distribution = nltk.FreqDist(cleaned_words)
    return distribution.most_common(10)

print(question_eight())

"""## Question 9 (1 point)

The 10 most frequent Porter stems of the alphabetic tokens. *Returns a list of 10 `(stem, frequency)` tuples sorted by decreasing frequency.*
"""

def question_nine():
    # Get the top 10 porter stems of alphabetic tokens
    stemmer = PorterStemmer()
    stems = [stemmer.stem(token) for token in moby_tokens if token.isalpha()]
    distribution = nltk.FreqDist(stems)
    return distribution.most_common(10)

print(question_nine())

"""## Question 10 (1 point)

Preprocess the first 1 000 characters of the novel: tokenize, lowercase, keep alphabetic tokens, remove stop words, lemmatize (default noun POS). *Returns the list of tokens.*
"""

def question_ten():
    # Preprocess the first 1000 characters of raw text
    first_thousand_chars = moby_raw[:1000]
    tokens = word_tokenize(first_thousand_chars)
    english_stops = set(stopwords.words("english"))
    lemmatizer = WordNetLemmatizer()

    final_tokens = []
    for token in tokens:
        lowered = token.lower()
        if lowered.isalpha() and lowered not in english_stops:
            final_tokens.append(lemmatizer.lemmatize(lowered))

    return final_tokens

r = question_ten()
